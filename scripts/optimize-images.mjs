/**
 * Image pipeline.
 *
 * Put original photos (JPG/PNG/WebP) in /images-src, then run `npm run images`.
 * For each file it writes responsive WebP versions to /public/images and
 * regenerates src/content/images.generated.ts (dimensions, srcset and a
 * placeholder colour), which the <Picture> component reads.
 *
 * To replace a photo, overwrite the file in /images-src with the same name and
 * run the script again. Nothing else needs to change.
 */
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const root = path.resolve(import.meta.dirname, '..');
const srcDir = path.join(root, 'images-src');
const outDir = path.join(root, 'public', 'images');
const manifestFile = path.join(root, 'src', 'content', 'images.generated.ts');

const WIDTHS = [480, 800, 1200, 1800, 2400];
const QUALITY = 74;

fs.mkdirSync(outDir, { recursive: true });

const files = fs
  .readdirSync(srcDir)
  .filter((f) => /\.(jpe?g|png|webp)$/i.test(f))
  .sort();

const manifest = {};

for (const file of files) {
  const name = path.parse(file).name;
  const input = path.join(srcDir, file);
  const base = sharp(input).rotate();
  const meta = await base.metadata();
  const widths = WIDTHS.filter((w) => w <= meta.width);
  if (!widths.length) widths.push(meta.width);

  const variants = [];
  for (const w of widths) {
    const outName = `${name}-${w}.webp`;
    const outPath = path.join(outDir, outName);
    if (!fs.existsSync(outPath) || fs.statSync(outPath).mtimeMs < fs.statSync(input).mtimeMs) {
      await sharp(input).rotate().resize({ width: w }).webp({ quality: QUALITY, effort: 5 }).toFile(outPath);
    }
    variants.push({ w, url: `/images/${outName}` });
  }

  const { dominant } = await sharp(input).resize(64).stats();
  const hex = '#' + [dominant.r, dominant.g, dominant.b].map((v) => v.toString(16).padStart(2, '0')).join('');

  manifest[name] = {
    width: meta.width,
    height: meta.height,
    src: variants[Math.min(1, variants.length - 1)].url,
    srcSet: variants.map((v) => `${v.url} ${v.w}w`).join(', '),
    color: hex,
  };
  console.log(`✓ ${name} (${widths.join(', ')})`);
}

const body = `// AUTO-GENERATED by scripts/optimize-images.mjs. Do not edit by hand.
// Run \`npm run images\` after adding or replacing files in /images-src.

export interface ImageAsset {
  width: number;
  height: number;
  src: string;
  srcSet: string;
  color: string;
}

export const images = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<string, ImageAsset>;

export type ImageName = keyof typeof images;
`;
fs.writeFileSync(manifestFile, body);
console.log(`\nWrote ${files.length} images to public/images and ${path.relative(root, manifestFile)}`);
